-- Reject non-UF accounts at the database boundary, including direct Auth API signup.
create function private.handle_auth_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.email is null or lower(new.email) !~ '^[^@[:space:]]+@ufl[.]edu$' then
    raise exception 'A UF email address is required';
  end if;
  if tg_op = 'INSERT' then
    insert into public.profiles(id,handle) values(new.id,'crumb-' || replace(new.id::text,'-',''));
  end if;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function private.handle_auth_user();
create trigger on_auth_email_changed before update of email on auth.users for each row execute function private.handle_auth_user();

create function public.category_ttl(cat public.crumb_category) returns interval
language sql immutable set search_path = '' as $$
  select case cat
    when 'event' then interval '3 hours' when 'freebie' then interval '1 hour'
    when 'crowd' then interval '30 minutes' when 'construction' then interval '24 hours'
    when 'hazard' then interval '2 hours' when 'sighting' then interval '30 minutes' end
$$;
create function public.loaf_state(c public.crumbs) returns text
language sql stable set search_path = '' as $$
  select case
    when c.status <> 'active' or c.expires_at <= now() then 'toast'
    when now() - c.last_confirmed_at >= public.category_ttl(c.category)/2 then 'stale'
    when c.confirm_count >= 3 and c.confirm_count > c.dispute_count then 'full_loaf'
    when c.confirm_count >= 1 then 'rising' else 'crumb' end
$$;
create function private.assert_actor(uid uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  -- Lock the profile against concurrent suspension/ban changes for this write.
  perform 1 from public.profiles p join auth.users u on u.id = p.id
    where p.id = uid and not p.banned
      and (p.suspended_until is null or p.suspended_until <= now())
      and u.email_confirmed_at is not null and lower(u.email) ~ '^[^@[:space:]]+@ufl[.]edu$'
    for share of p;
  if not found then raise exception 'Confirmed active UF account required'; end if;
end $$;
create function private.prepare_crumb() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  perform private.assert_actor(new.user_id);
  new.expires_at := coalesce(new.expires_at,now() + public.category_ttl(new.category));
  return new;
end $$;
create trigger crumbs_prepare before insert on public.crumbs for each row execute function private.prepare_crumb();

create function private.prepare_interaction() returns trigger
language plpgsql security definer set search_path = '' as $$
declare c public.crumbs;
begin
  -- Every interaction locks the parent first, serializing moderation per crumb.
  select * into c from public.crumbs where id = new.crumb_id for update;
  if not found or c.status <> 'active' or c.expires_at <= now() then raise exception 'Crumb is no longer active'; end if;
  perform private.assert_actor(new.user_id);
  if tg_op = 'UPDATE' and (new.crumb_id <> old.crumb_id or new.user_id <> old.user_id) then
    raise exception 'Interaction identity cannot change';
  end if;
  if tg_table_name = 'votes' then
    if c.user_id = new.user_id then raise exception 'Cannot vote on your own crumb'; end if;
    if tg_op = 'INSERT' then new.created_at := now();
    elsif new.value is distinct from old.value then new.created_at := now();
    else new.created_at := old.created_at; end if;
  end if;
  return new;
end $$;
create trigger votes_prepare before insert or update on public.votes for each row execute function private.prepare_interaction();
create trigger reports_prepare before insert on public.crumb_reports for each row execute function private.prepare_interaction();

create function private.notify_crumb(c public.crumbs,is_full boolean) returns void
language sql security definer set search_path = '' as $$
  insert into public.notifications(user_id,crumb_id,title,body)
  select distinct s.user_id,c.id,
    case when is_full then 'Full Loaf: ' else 'Community crumb: ' end || c.title,
    coalesce(p.name,'On campus')
  from public.subscriptions s join public.profiles recipient on recipient.id = s.user_id
  left join public.places p on p.id = c.place_id
  where s.user_id <> c.user_id and not recipient.banned
    and (cardinality(s.categories) = 0 or c.category = any(s.categories))
    and (is_full or not s.full_loaf_only) and (c.category <> 'sighting' or is_full)
    and (s.kind = 'campus' or (s.kind = 'place' and s.place_id = c.place_id))
  on conflict (user_id,crumb_id) do nothing
$$;
create function private.on_crumb_created() returns trigger
language plpgsql security definer set search_path = '' as $$
begin perform private.notify_crumb(new,false); return new; end $$;
create trigger crumbs_notify after insert on public.crumbs for each row execute function private.on_crumb_created();

-- Bans immediately stop existing votes from contributing to public counts.
create function private.on_profile_banned() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.banned is distinct from old.banned then
    update public.crumbs c set
      confirm_count = (select count(*) from public.votes v join public.profiles p on p.id = v.user_id where v.crumb_id = c.id and v.value = 1 and not p.banned),
      dispute_count = (select count(*) from public.votes v join public.profiles p on p.id = v.user_id where v.crumb_id = c.id and v.value = -1 and not p.banned),
      last_confirmed_at = coalesce((select max(v.created_at) from public.votes v join public.profiles p on p.id = v.user_id where v.crumb_id = c.id and v.value = 1 and not p.banned),c.created_at)
    where c.id in (select v.crumb_id from public.votes v where v.user_id = new.id);
  end if;
  return new;
end $$;
create trigger profiles_ban_votes after update of banned on public.profiles for each row execute function private.on_profile_banned();

create function private.evaluate_crumb() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  c public.crumbs; confirms integer; disputes integer; reports integer; strikes_count integer;
  confirming boolean := false; was_full boolean; why text; latest timestamptz;
begin
  select * into c from public.crumbs where id = new.crumb_id for update;
  if c.status <> 'active' then return new; end if;
  if tg_table_name = 'votes' then
    if tg_op = 'INSERT' then confirming := new.value = 1;
    else confirming := new.value = 1 and old.value <> 1; end if;
  end if;
  was_full := public.loaf_state(c) = 'full_loaf';
  select count(*) filter(where v.value = 1),count(*) filter(where v.value = -1),max(v.created_at) filter(where v.value = 1)
    into confirms,disputes,latest from public.votes v join public.profiles p on p.id = v.user_id
    where v.crumb_id = c.id and not p.banned;
  select count(*) into reports from public.crumb_reports r join public.profiles p on p.id = r.user_id
    where r.crumb_id = c.id and r.reason in ('harassment','privacy') and not p.banned;
  update public.crumbs set confirm_count = confirms,dispute_count = disputes,
    last_confirmed_at = coalesce(latest,c.created_at),
    expires_at = case when confirming and category <> 'crowd' then greatest(expires_at,now() + public.category_ttl(category)) else expires_at end
    where id = c.id returning * into c;
  if reports >= 2 then why := 'harassment_or_privacy';
  elsif disputes - confirms >= 3 then why := 'disputed'; end if;
  if why is not null then
    update public.crumbs set status = 'removed',removed_reason = why,title = '[removed]',description = null,embedding = null where id = c.id;
    delete from public.notifications where crumb_id = c.id;
    insert into public.strikes(user_id,crumb_id,reason) values(c.user_id,c.id,why) on conflict(crumb_id) do nothing;
    -- Serialize strike counting across different crumbs by the same author.
    perform 1 from public.profiles where id = c.user_id for update;
    select count(*) into strikes_count from public.strikes where user_id = c.user_id and created_at > now() - interval '30 days';
    if strikes_count >= 3 then update public.profiles set banned = true where id = c.user_id;
    elsif strikes_count = 2 then update public.profiles set suspended_until = now() + interval '24 hours' where id = c.user_id; end if;
  elsif not was_full and public.loaf_state(c) = 'full_loaf' then perform private.notify_crumb(c,true);
  end if;
  return new;
end $$;
create trigger votes_evaluate after insert or update on public.votes for each row execute function private.evaluate_crumb();
create trigger reports_evaluate after insert on public.crumb_reports for each row execute function private.evaluate_crumb();

